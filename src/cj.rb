    def ensure_tag(model, name)
      return nil if name.nil? || name.strip.empty?

      tags = model.layers
      tag = tags[name]
      tag ||= tags.add(name)
      tag
    end

    def ray_vectors
      @ray_vectors ||= begin
        vectors = RAY_VECTORS_RAW.each_line.filter_map do |line|
          s = line.strip
          next if s.empty? || s.start_with?('#')

          m = s.match(/\{\s*([-+]?\d*\.?\d+)\s*,\s*([-+]?\d*\.?\d+)\s*,\s*([-+]?\d*\.?\d+)\s*\}/)
          next unless m

          x = m[1].to_f
          y = m[2].to_f
          z = m[3].to_f

          v = Geom::Vector3d.new(x, y, z)
          next if v.length == 0.0

          v.normalize!
          v
        end

        log("Loaded #{vectors.length} ray vectors")
        vectors
      end
    end

    # Returns [hit_point(Geom::Point3d), distance(Float)] or nil
    def raycast_world(model, origin, dir)
      d = dir.clone
      d.normalize!

      ray = [origin, d]
      hit = model.raytest(ray, true) # Ignore hidden geometry, including temporarily hidden results.
      return nil unless hit

      hit_pt = hit[0]
      [hit_pt, origin.distance(hit_pt)]
    end

    def result_groups(model)
      collections = [model.entities] + model.definitions.map(&:entities)
      collections.flat_map { |entities| entities.select do |entity|
        next false unless entity.is_a?(Sketchup::Group) || entity.is_a?(Sketchup::ComponentInstance)
        entity.get_attribute('CJ_Insolation', 'result', false) ||
          (entity.name.match?(/\AInsolation_\d{8}_\d{6}\z/) && entity.layer.name == DEFAULT_TAG_NAME)
      end }.uniq
    end

    def raycast_exclusions(model)
      result_groups(model) + (defined?(CJ::SavedPoints) ? CJ::SavedPoints.all(model) : [])
    end

    def without_results(model)
      states = raycast_exclusions(model).map { |group| [group, group.hidden?] }
      begin
        states.each { |group, _hidden| group.hidden = true }
        yield
      ensure
        states.each { |group, hidden| group.hidden = hidden if group.valid? }
      end
    end

    def calculate_points(model, points)
      raise ArgumentError, 'Нет выбранных точек' if points.empty?
      vectors = ray_vectors
      raise ArgumentError, 'Список векторов пуст' if vectors.empty?
      without_results(model) do
        points.map do |origin|
          results = vectors.each_with_index.map do |dir, i|
            hit = raycast_world(model, origin, dir)
            { i: i, dir: dir, hit_dist: hit && hit[1], hit_pt: hit && hit[0] }
          end
          { origin: origin.clone, results: results }
        end
      end
    end

    def surface_annotations(results)
      counters = { false => 0, true => 0 }
      entries = results.map do |result|
        blocked = !result[:hit_dist].nil?
        entry = { result: result, blocked: blocked, minute: counters[blocked] + 1 }
        counters[blocked] += 1
        entry
      end
      entries.each_with_index.flat_map do |entry, index|
        previous = index > 0 ? entries[index - 1] : nil
        following = entries[index + 1]
        roles = []
        roles << [:start, previous] if previous.nil? || previous[:blocked] != entry[:blocked]
        roles << [:end, following] if following.nil? || following[:blocked] != entry[:blocked]
        roles.map do |role, neighbor|
          direction = entry[:result][:dir].clone
          direction = direction + neighbor[:result][:dir] if neighbor && neighbor[:blocked] != entry[:blocked]
          direction.normalize! unless direction.length == 0
          entry.merge(role: role, direction: direction)
        end
      end
    end

    def add_surface(entities, origin, results, maxlen)
      layers = CJ::ResultStyle.tags(Sketchup.active_model)
      palette = [['CJ_Surface_Green_50', [0, 200, 0]], ['CJ_Surface_Red_50', [255, 0, 0]]].map do |name, color|
        material = Sketchup.active_model.materials[name] || Sketchup.active_model.materials.add(name)
        material.color = color
        material.alpha = 0.5
        material
      end
      triangles = []
      results.each_cons(2) do |left, right|
        left_length = left[:hit_dist] || maxlen
        right_length = right[:hit_dist] || maxlen
        a = origin.offset(left[:dir], left_length)
        b = origin.offset(right[:dir], right_length)
        left_status = left[:hit_dist] ? 1 : 0
        right_status = right[:hit_dist] ? 1 : 0
        if left_status == right_status
          triangles << [[origin, a, b], left_status]
        else
          middle = left[:dir] + right[:dir]
          next if middle.length == 0
          middle.normalize!
          # Split the visual sector at its angular midpoint; no extra ray tests.
          triangles << [[origin, a, origin.offset(middle, left_length)], left_status]
          triangles << [[origin, origin.offset(middle, right_length), b], right_status]
        end
      end
      entities.build do |builder|
        triangles.each do |points, status|
          next if points[1].distance(origin) < 0.1.mm || points[2].distance(origin) < 0.1.mm
          next if (points[1] - origin).cross(points[2] - origin).length < 1e-9
          face = builder.add_face(points)
          next unless face
          face.material = palette[status]
          face.back_material = palette[status]
          face.layer = layers[status == 0 ? :green : :red]
        end
      end
      entities.grep(Sketchup::Edge).each do |edge|
        faces = edge.faces
        edge.layer = faces.first.layer unless faces.empty?
        next unless faces.length == 2 && faces[0].material.color == faces[1].material.color
        edge.soft = true
        edge.smooth = true
      end
      surface_annotations(results).each do |entry|
        result = entry[:result]
        direction = entry[:direction]
        length = result[:hit_dist] || maxlen
        next if length < 1.mm
        neighbor = results.find { |r| r[:i] != result[:i] }
        next unless neighbor
        normal = result[:dir].cross(neighbor[:dir])
        next if normal.length == 0
        normal.normalize!
        anchor = origin.offset(direction, length).offset(normal, 0.02.m)
        marker = entities.add_group
        marker.name = "#{entry[:minute]} мин — #{entry[:blocked] ? 'тень' : 'солнце'}"
        marker.layer = layers[:labels]
        marker.set_attribute('CJ_Insolation', 'ray', result[:i])
        marker.set_attribute('CJ_Insolation', 'blocked', entry[:blocked])
        marker.set_attribute('CJ_Insolation', 'minute', entry[:minute])
        marker.set_attribute('CJ_Insolation', 'boundary_role', entry[:role].to_s)
        edges = marker.entities.add_circle(anchor, normal, [0.06.m, length * 0.002].max, 12)
        face = marker.entities.add_face(edges)
        if face
          face.material = 'black'
          face.back_material = 'black'
          edges.each { |edge| edge.hidden = true }
        end
        label = "#{entry[:minute]}-я минута #{entry[:blocked] ? 'затенения' : 'инсоляции'}"
        marker.entities.add_text(label, anchor, Geom::Vector3d.new(0, 0, [1.m, length * 0.015].max))
      end
    end

    def build_batch(model, calculations, mode: :lines)
      raise ArgumentError, 'Неизвестный режим отображения' unless [:lines, :surface, :summary].include?(mode)
      layers = CJ::ResultStyle.tags(model)
      batch = model.entities.add_group
