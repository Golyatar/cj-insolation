      batch.layer = model.layers[0]
      batch.set_attribute('CJ_Insolation', 'result', true)
      batch.set_attribute('CJ_Insolation', 'version', 2)
      batch.set_attribute('CJ_Insolation', 'display_mode', mode.to_s)
      batch.set_attribute('CJ_Insolation', 'batch_id', SecureRandom.uuid)
      batch.set_attribute('CJ_Insolation', 'created_at', Time.now.strftime('%Y-%m-%d %H:%M:%S %z'))
      existing_numbers = model.definitions.flat_map do |definition|
        definition.entities.grep(Sketchup::Group).filter_map do |group|
          next unless group.get_attribute('CJ_Insolation', 'origin')
          group.get_attribute('CJ_Insolation', 'point_number') || group.name[/\AТочка (\d+)\z/, 1]&.to_i
        end
      end
      first_number = [model.get_attribute('CJ_Insolation', 'next_point_number', 1), (existing_numbers.max || 0) + 1].max
      model.set_attribute('CJ_Insolation', 'next_point_number', first_number + calculations.length)
      batch.set_attribute('CJ_Insolation', 'first_point_number', first_number)
      maxlen = (DEFAULT_MAX_LEN_M * 1000.0).mm
      calculations.each_with_index do |calculation, index|
        group = batch.entities.add_group
        number = first_number + index
        group.name = "Точка #{number}"
        group.set_attribute('CJ_Insolation', 'point_number', number)
        group.set_attribute('CJ_Insolation', 'source_id', calculation[:source_id]) if calculation[:source_id]
        origin = calculation[:origin]
        results = calculation[:results]
        group.set_attribute('CJ_Insolation', 'origin', origin.to_a)
        group.set_attribute('CJ_Insolation', 'clear_count', clear_streaks(results).sum)
        ([:summary, :surface].include?(mode) ? [] : results).each do |result|
          length = result[:hit_dist] || maxlen
          color = result[:hit_dist] ? Sketchup::Color.new(255, 0, 0) : Sketchup::Color.new(0, 200, 0)
          edge = group.entities.add_line(origin, origin.offset(result[:dir], length))
          edge.material = color if edge
          edge.layer = layers[result[:hit_dist] ? :red : :green] if edge
        end
        add_surface(group.entities, origin, results, maxlen) if mode == :surface
        add_result_label(group.entities, origin, results, point_number: number)
        assessment = assess_insolation(results)
        group.set_attribute('CJ_Insolation', 'passed', assessment[:passed])
        CJ::ResultStyle.marker(group.entities, calculation, assessment[:passed], layers)
      end
      batch
    end

    def assess_insolation(results)
      segments = clear_streaks(results).map { |count| count * TIME_STEP_MINUTES }
      total = segments.sum
      longest = segments.max || 0
      continuous = longest >= 90
      intermittent = segments.length >= 2 && total >= 120 && longest >= 60
      reasons = []
      reasons << 'Непрерывный интервал не менее 90 минут' if continuous
      reasons << 'Суммарно не менее 120 минут и интервал не менее 60 минут' if intermittent
      { passed: continuous || intermittent, continuous: continuous, intermittent: intermittent,
        total_minutes: total, max_minutes: longest, segments_minutes: segments,
        reason: reasons.empty? ? 'Не выполнено ни одно условие' : reasons.join('; ') }
    end

    CALCULATION_RAYS_PER_TICK = 24

    def progress_dialog
      dialog = UI::HtmlDialog.new(dialog_title: 'CJ — расчёт инсоляции',
                                  preferences_key: 'CJ_CalculationProgress_v1',
                                  width: 360, height: 150, resizable: false,
                                  style: UI::HtmlDialog::STYLE_DIALOG)
      dialog.set_html(<<~HTML)
        <!doctype html><html lang="ru"><meta charset="utf-8"><style>
        body{font:14px 'Segoe UI',Arial,sans-serif;margin:18px;color:#202832}
        #label{margin-bottom:10px} progress{width:100%;height:18px}
        button{margin-top:14px;padding:7px 18px}
        </style><div id="label">Подготовка расчёта…</div>
        <progress id="bar" max="100" value="0"></progress>
        <button onclick="sketchup.cancel_calculation()">Отменить</button>
        <script>function updateProgress(done,total){
          const p=total?Math.floor(done*100/total):0;
          document.getElementById('bar').value=p;
          document.getElementById('label').textContent='Проверено лучей: '+done+' из '+total+' ('+p+'%)';
        }</script></html>
      HTML
