    def clear_streaks(results)
      streaks = []
      current = 0

      results.each do |r|
        if r[:hit_dist].nil?
          current += 1
        else
          if current > 0
            streaks << current
            current = 0
          end
        end
      end
      streaks << current if current > 0
      streaks
    end

    def add_result_label(entities, origin, results, point_number: nil)
      streaks = clear_streaks(results)
      total = streaks.sum

      text =
        if streaks.empty?
          "0. Суммарно = 0"
        else
          "#{streaks.join(', ')}. Суммарно = #{total}"
        end

      offset = Geom::Vector3d.new(0, 0, L_OFFSET.mm)
      label = entities.add_text(text, origin, offset)
      label.layer = CJ::ResultStyle.tags(Sketchup.active_model)[:labels]

      log("Label: #{text}")
    end

